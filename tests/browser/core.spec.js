import { test, expect } from '@playwright/test'

const key = 'xiangshiji:formal:v1'
async function open(page, path = '/') {
  await page.goto('/#' + path)
  await expect(page.locator('main h1').first()).toBeVisible()
}

test('地图无弹框侧栏、点击选省、地区下拉和筛选', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await open(page, '/map')
  await expect(page.locator('.province-target')).toHaveCount(34)
  await page.locator('[data-map-code="420000"]').dispatchEvent('pointerenter', { pointerType: 'mouse' })
  await expect(page.locator('.province-hover-layer')).toHaveClass(/visible/)
  await expect(page.locator('#atlas-tooltip, .atlas-aside, #atlas-preview')).toHaveCount(0)
  await page.locator('[data-map-code="420000"]').focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/province/)
  await expect(page.getByRole('heading', { name: '湖北，有滋有味' })).toBeVisible()
  await page.locator('#type-filter').selectOption('甜品')
  await expect(page.getByRole('heading', { name: '这一页，还没有收录' })).toBeVisible()
  await page.getByRole('button', { name: '清除筛选' }).click()
  await expect(page.locator('.food-entry')).toHaveCount(8)
  await open(page, '/map')
  await page.locator('#atlas-select').selectOption('330000')
  await expect(page.getByRole('heading', { name: '浙江，有滋有味' })).toBeVisible()
  await open(page, '/map')
  await page.locator('#atlas-select').selectOption('370000')
  await expect(page.locator('#toast')).toContainText('山东')
  expect(errors).toEqual([])
})

