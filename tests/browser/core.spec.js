test('保存失败不显示成功状态，图片加载失败可读，未知页面可返回', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Storage denied', 'QuotaExceededError') } })
  await page.route('**/assets/noodles-sticker.webp', route => route.abort())
  await open(page, '/food/noodles')
  await page.getByRole('button', { name: '收藏', exact: true }).click()
  await expect(page.locator('.storage-warning')).toContainText('本地保存失败')
  await expect(page.getByRole('button', { name: '收藏', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.dish-portrait img')).toHaveClass(/image-failed/)
  await expect(page.locator('.dish-portrait img')).toHaveAttribute('alt', /暂时无法显示/)
  await open(page, '/missing-page')
  await expect(page.getByRole('heading', { name: '这条小巷，还未走到' })).toBeVisible()
  await page.locator('main').getByRole('link', { name: '回到首页' }).click()
  await expect(page.getByRole('heading', { name: '循着烟火，寻味中国' })).toBeVisible()
})

