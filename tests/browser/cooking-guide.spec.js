import { test, expect } from '@playwright/test'

for (const width of [1440, 720]) {
  test(`阿云单气泡与下方操作区完整流程 ${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height:1000 })
    const errors=[]
    page.on('pageerror', e=>errors.push(e.message))
    await page.goto('/#/cook/sesame-noodles')
    const button=name=>page.getByRole('button',{name,exact:true})
    const bubble=page.locator('#cook-dialogue')
    const phase=page.locator('.cook-phase')
    const next=page.getByRole('button',{name:'下一步'})
    const lift=page.getByLabel('提起漏勺',{exact:true})
    const mix=page.getByLabel('拌匀进度',{exact:true})
    async function layout() {
      await expect(page.locator('.station-speech')).toHaveCount(1)
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
      const b=await bubble.boundingBox(), scene=await page.locator('.workstation-canvas').boundingBox(), controls=await page.locator('.cook-controls').boundingBox()
      expect(controls.y).toBeGreaterThanOrEqual(scene.y+scene.height)
      expect(await bubble.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
      for(const selector of ['.ingredient-drawer','.seasoning-shelf','.bowl-workspace','.cook-next']) {
        const r=await page.locator(selector).boundingBox()
        expect(b.x+b.width<=r.x || r.x+r.width<=b.x || b.y+b.height<=r.y || r.y+r.height<=b.y,selector+' 与气泡不重叠').toBe(true)
      }
    }
    await expect(page.locator('.ingredient-object')).toHaveCount(4)
    for (const slot of await page.locator('button.ingredient-slot').all()) {
      const art=await slot.locator('.ingredient-row-icon, .ingredient-object').boundingBox()
      const label=await slot.locator('.slot-caption').boundingBox()
      expect(art.y+art.height).toBeLessThanOrEqual(label.y+1)
      expect(await slot.locator('.slot-caption').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
    }
    await expect(bubble).toContainText('点一下漏勺')
    await expect(lift).toBeDisabled()
    await button('面粉').click()
    await expect(bubble).toContainText('咱们这步用漏勺')
    await layout()
    await button('漏勺').click()
    await expect(bubble).toContainText('制作台下方')
    await lift.scrollIntoViewIfNeeded()
    const slider=await lift.boundingBox()
    await page.mouse.move(slider.x+8,slider.y+slider.height/2)
    await page.mouse.down()
    await page.mouse.move(slider.x+slider.width-2,slider.y+slider.height/2,{steps:15})
    await page.mouse.up()
    await expect(phase).toContainText('已完成')
    await button('漏勺').click()
    await expect(lift).toHaveValue('100')
    await next.click()
    await expect(bubble).toContainText('点一下芝麻酱')
    await button('粽叶').click()
    await expect(bubble).toContainText('咱们这步用芝麻酱')
    await button('芝麻酱').click()
    await expect(bubble).toContainText('按住鼠标左键来回拖动')
    await layout()
    await page.locator('.bowl-workspace').scrollIntoViewIfNeeded()
    const bowl=await page.locator('.bowl-workspace').boundingBox()
    await page.mouse.move(bowl.x+30,bowl.y+50)
    await page.mouse.down({button:'right'})
    await page.mouse.move(bowl.x+bowl.width-30,bowl.y+50,{steps:4})
    await page.mouse.up({button:'right'})
    await expect(phase).toContainText('0%')
    await page.mouse.move(bowl.x+30,bowl.y+50)
    await page.mouse.down()
    await page.mouse.move(bowl.x+80,bowl.y+50,{steps:3})
    await page.mouse.up()
    await expect(bubble).toContainText('按住鼠标左键来回拖动')
    const partial=await phase.innerText()
    await button('芝麻酱').click()
    await expect(phase).toHaveText(partial)
    await page.locator('.bowl-workspace').scrollIntoViewIfNeeded()
    const r=await page.locator('.bowl-workspace').boundingBox()
    await page.mouse.move(r.x+20,r.y+50)
    await page.mouse.down()
    for(let i=0;i<10;i++)await page.mouse.move(r.x+(i%2?20:r.width-20),r.y+50,{steps:4})
    await page.mouse.up()
    await expect(phase).toContainText('已完成')
    await next.click()
    await button('面粉').click()
    await expect(bubble).toContainText('咱们这步用萝卜丁与葱花')
    await expect(page.locator('.working-bowl')).toHaveAttribute('src', /cook-plain-bowl/)
    await expect(page.locator('.garnish-morsels')).toHaveCount(0)
    await button('萝卜丁与葱花').click()
    await expect(bubble).toContainText('点一点碗里的三个小圈')
    await expect(page.locator('.garnish-ring')).toHaveCount(3)
    for (const target of await page.locator('.garnish-targets button').all()) {
      expect(await target.innerText()).toBe('')
      const size=await target.boundingBox()
      expect(size.width).toBeGreaterThanOrEqual(44)
      expect(size.height).toBeGreaterThanOrEqual(44)
    }
    await layout()
    await page.screenshot({path:testInfo.outputPath('sprinkle.png'),fullPage:true})
    await button('在面碗左侧撒料').click()
    await button('在面碗左侧撒料').click()
    await button('萝卜丁与葱花').click()
    await expect(phase).toContainText('1 / 3')
    await expect(page.locator('.garnish-morsels')).toHaveCount(1)
    await expect(page.locator('.garnish-ring')).toHaveCount(2)
    expect(await page.locator('.garnish-morsels').evaluate(el=>getComputedStyle(el).animationName)).toBe('garnish-fall')
    await expect(button('盛出这一碗')).toBeDisabled()
    await button('在面碗中间撒料').click()
    await button('在面碗右侧撒料').click()
    await expect(page.locator('.garnish-morsels')).toHaveCount(3)
    await expect(page.locator('.garnish-ring')).toHaveCount(0)
    await page.waitForTimeout(500)
    await page.screenshot({path:testInfo.outputPath('garnished.png'),fullPage:true})
    await expect(bubble).toContainText('点击“盛出这一碗”')
    await button('盛出这一碗').click()
    await expect(page.getByRole('heading',{name:'这一碗，拌好了。',exact:true})).toBeVisible()
    const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('xiangshiji:formal:v1')))
    expect(stored.cooking['sesame-noodles']).toBe(true)
    expect(stored.stories).toEqual({})
    await button('再做一碗').click()
    await expect(phase).toHaveText('待选择 · 0%')
    await expect(page.locator('.garnish-morsels')).toHaveCount(0)
    await page.emulateMedia({reducedMotion:'reduce'})
    await button('漏勺').focus();await page.keyboard.press('Enter')
    await lift.focus();await page.keyboard.press('End')
    await next.focus();await page.keyboard.press('Enter')
    await button('芝麻酱').focus();await page.keyboard.press('Enter')
    await page.getByText('操作帮助',{exact:true}).focus();await page.keyboard.press('Enter')
    await mix.focus();await page.keyboard.press('ArrowRight')
    await expect(mix).toHaveValue('1')
    await page.keyboard.press('End')
    await next.focus();await page.keyboard.press('Enter')
    await button('萝卜丁与葱花').focus();await page.keyboard.press('Enter')
    await expect(phase).toContainText('0 / 3')
    for(const side of ['左侧','中间','右侧']) {await button('在面碗'+side+'撒料').focus();await page.keyboard.press('Space')}
    await expect(page.locator('.garnish-morsels')).toHaveCount(3)
    expect(await page.locator('.garnish-morsels').first().evaluate(el=>getComputedStyle(el).animationName)).toBe('none')
    await button('盛出这一碗').focus();await page.keyboard.press('Enter')
    await expect(button('再做一碗')).toBeVisible()
    expect(errors).toEqual([])
  })
}
