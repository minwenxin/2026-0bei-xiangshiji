import { test, expect } from '@playwright/test'

const close = page => page.getByRole('button', { name: '关闭小记' })
const reader = page => page.getByRole('dialog', { name: '广场手记' })

test('桌面阅读卡保留广场筛选与滚动，Esc 和浏览器返回恢复入口焦点', async ({ page }, info) => {
  await page.addInitScript(() => {
    localStorage.setItem('xiangshiji:formal:v1', JSON.stringify({
      posts: [{ id: 'long-note', title: '街边长篇手记', region: '江苏', body: '这一口值得慢慢读。\n'.repeat(240) }],
    }))
  })
  await page.goto('/#/square')
  await page.getByRole('button', { name: '食客分享', exact: true }).click()
  await page.getByRole('combobox', { name: '筛选地区' }).selectOption('江苏')
  const search = page.getByRole('searchbox')
  await search.fill('长篇')
  const opener = page.locator('.square-masonry .post-preview')
  await opener.focus()
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
  const scrollBefore = await page.evaluate(() => scrollY)
  expect(scrollBefore).toBeGreaterThan(0)
  await opener.press('Enter')
  await expect(page).toHaveURL(/post\/long-note/)
  await expect(reader(page)).toBeVisible()
  await expect(close(page)).toBeFocused()
  await expect(reader(page).locator('img')).toHaveCount(0)
  const box = await reader(page).boundingBox()
  expect(box.width).toBeGreaterThanOrEqual(720)
  expect(box.width).toBeLessThanOrEqual(800)
  expect(box.height).toBeLessThanOrEqual(900 * .85 + 1)
  await page.screenshot({ path: info.outputPath('reader-desktop.png') })
  await page.locator('.square-search input').evaluate(input => input.focus())
  await expect(close(page)).toBeFocused()
  await page.mouse.move(30, 300)
  await page.mouse.wheel(0, -500)
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scrollBefore)
  const content = reader(page).locator('.post-reader-content')
  await content.hover()
  await page.mouse.wheel(0, 900)
  await expect.poll(() => content.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scrollBefore)
  await expect(close(page)).toBeInViewport()
  await page.keyboard.press('Tab')
  expect(await reader(page).evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(reader(page)).toHaveCount(0)
  await expect(opener).toBeFocused()
  await expect(search).toHaveValue('长篇')
  await expect(page.getByRole('combobox', { name: '筛选地区' })).toHaveValue('江苏')
  await expect(page.getByRole('button', { name: '食客分享', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scrollBefore)
  await opener.press('Enter')
  await expect(reader(page)).toBeVisible()
  await page.goBack()
  await expect(opener).toBeFocused()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scrollBefore)
})

test('窄屏底部阅读卡与独立页共享互动，保留示例标识和图片失败反馈', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/square')
  const opener = page.locator('.recommendation-story a[href="#/post/note-noodles"]')
  await opener.click()
  const dialog = reader(page)
  await expect(dialog.getByRole('heading', { name: '武汉的早晨，从一碗热干面开始' })).toBeVisible()
  await expect(dialog).toContainText('虚构示例')
  const photo = dialog.locator('.post-detail-image')
  await photo.evaluate(img => img.decode())
  const dimensions = await photo.evaluate(img => ({
    ratio: img.width / img.height,
    original: img.naturalWidth / img.naturalHeight,
    height: img.height,
  }))
  expect(dimensions.ratio).toBeCloseTo(dimensions.original, 1)
  expect(dimensions.height).toBeLessThanOrEqual(340)
  const box = await dialog.boundingBox()
  expect(box.y).toBeGreaterThan(40)
  expect(box.y + box.height).toBeCloseTo(844, 0)
  expect(box.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: info.outputPath('reader-mobile.png') })
  await dialog.getByRole('button', { name: '喜欢', exact: true }).click()
  await dialog.getByRole('button', { name: '收藏', exact: true }).click()
  await dialog.getByLabel('本地留言').fill('留在同一本手记里。')
  await dialog.getByRole('button', { name: '保存留言' }).click()
  await expect(dialog.locator('#comments')).toContainText('留在同一本手记里。')
  await close(page).click()
  await expect(opener).toBeFocused()
  await opener.click()
  await expect(dialog).toBeVisible()
  await page.reload()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.post-reader-page')).toBeVisible()
  await expect(page.getByRole('button', { name: '取消喜欢' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: '取消收藏' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#comments')).toContainText('留在同一本手记里。')
  await page.route('**/assets/community-notes/note-noodles.jpeg', route => route.abort())
  await page.reload()
  await expect(page.getByText('配图暂时无法显示，正文仍可阅读。')).toBeVisible()
  await expect(page.locator('.post-body')).toBeVisible()
  await page.goto('/#/post/missing')
  await expect(page.getByRole('heading', { name: '这篇小记暂时找不到了' })).toBeVisible()
  await page.goto('/#/square')
  await page.goto('/#/post/note-hulatang')
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.post-reader-page h1')).toHaveText('在河南，把油条泡进胡辣汤')
  await expect(page.locator('.post-reader-page .post-detail-image')).toBeVisible()
})

test('小编选题簿在同一个浮层内切换，正文回到顶部且一次返回广场', async ({ page }, info) => {
  await page.goto('/#/square')
  const opener = page.locator('.recommendation-story a[href="#/post/note-noodles"]')
  await opener.click()
  const dialog = reader(page)
  const index = dialog.getByRole('navigation', { name: '小编的选题簿' })
  await expect(index.getByRole('link')).toHaveCount(7)
  const active = index.getByRole('link', { name: '武汉的早晨，从一碗热干面开始' })
  await expect(active).toHaveAttribute('aria-current', 'page')
  const pane = dialog.locator('.post-reader-main')
  await pane.evaluate(el => { el.scrollTop = 500 })
  expect(await pane.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await index.getByRole('link', { name: '火锅里，能涮出多少种味道？' }).click()
  await expect(dialog.getByRole('heading', { name: '火锅里，能涮出多少种味道？' })).toBeVisible()
  await expect(index.getByRole('link', { name: '火锅里，能涮出多少种味道？' })).toHaveAttribute('aria-current', 'page')
  expect(await pane.evaluate(el => el.scrollTop)).toBe(0)
  await page.screenshot({ path: info.outputPath('reader-columns.png') })
  await page.goBack()
  await expect(page).toHaveURL(/#\/square$/)
  await expect(opener).toBeFocused()
  await opener.click()
  const mapLink = dialog.getByRole('link', { name: /已收录于美食地图.*查看武汉热干面/ })
  await expect(mapLink).toHaveAttribute('href', '#/food/noodles')
  await mapLink.click()
  await expect(page).toHaveURL(/#\/food\/noodles$/)
})

test('窄屏展开饭友目录，阿禾两篇可互换并能进入同一作者主页', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/post/note-wuchang-fish')
  const toggle = page.getByRole('button', { name: '这位饭友的小记' })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  const index = page.getByRole('navigation', { name: '这位饭友的小记' })
  await expect(index.getByRole('link')).toHaveCount(2)
  await expect(page.locator('.post-index-author')).toContainText('爱记武汉过早，也爱逛菜场。')
  await index.getByRole('link', { name: '三鲜豆皮，一口糯香' }).click()
  await expect(page.getByRole('heading', { name: '三鲜豆皮，一口糯香' })).toBeVisible()
  await expect(page.locator('.post-map-link')).toHaveCount(0)
  await toggle.click()
  await index.getByRole('link', { name: '清蒸武昌鱼，真的好嫩' }).click()
  await expect(page.getByRole('heading', { name: '清蒸武昌鱼，真的好嫩' })).toBeVisible()
  await toggle.click()
  await page.getByRole('link', { name: '查看巷口阿禾的主页' }).click()
  await expect(page).toHaveURL(/taster\/demo-yun/)
  await expect(page.locator('.scrapbook-post')).toHaveCount(2)
})
