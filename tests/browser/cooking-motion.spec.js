import { test,expect } from '@playwright/test'
import {button,blanch,mixNoodles,finishNoodles} from './cooking-helpers.js'
test('热干面动作：短按续接、取消、固定碗与有效拖动',async({page},testInfo)=>{
 await page.goto('/#/cook/sesame-noodles')
 await expect(page.locator('input[type=range]')).toHaveCount(0)
 await button(page,'漏勺').click()
 const tool=button(page,'按住漏勺烫面，松开提起'),next=page.getByRole('button',{name:'下一步'})
 await tool.focus();await page.keyboard.down('Space');await page.waitForTimeout(850);await page.keyboard.up('Space')
 await expect(page.locator('#cook-dialogue')).toContainText('再烫一会儿')
 await expect(next).toBeDisabled()
 await page.waitForTimeout(1500);await expect(next).toBeDisabled()
 await tool.focus();await page.keyboard.down('Space');await page.waitForTimeout(1200);await expect(next).toBeDisabled();await page.keyboard.up('Space')
 await expect(next).toBeEnabled()
 await mixNoodles(page,false)
 await expect(page.locator('.fixed-bowl')).toHaveCSS('transform','none')
 await expect(page.locator('.bowl-front')).toHaveCSS('transform','none')
 await page.screenshot({path:testInfo.outputPath('mixed.png'),fullPage:true})
})
for(const keyboard of [false,true])test(`热干面完整${keyboard?'键盘':'鼠标'}流程`,async({page},testInfo)=>{
 await page.goto('/#/cook/sesame-noodles');await finishNoodles(page,keyboard)
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('xiangshiji:formal:v1')))
 expect(stored.cooking).toEqual({'sesame-noodles':true});expect(stored.stories).toEqual({})
 await button(page,'再做一碗').click();await expect(page.locator('.cook-phase')).toContainText('待选择');await expect(page.locator('.garnish-morsels')).toHaveCount(0)
})

test('分层搅拌只移动面条局部，松开及取消立即停下',async({page},testInfo)=>{
 await page.goto('/#/cook/sesame-noodles');await blanch(page,true)
 await page.getByRole('button',{name:'下一步'}).click();await button(page,'芝麻酱').click()
 const bowl=page.getByRole('group',{name:'面碗搅拌区'});await bowl.scrollIntoViewIfNeeded();const r=await bowl.boundingBox()
 const fixedBefore=await page.locator('.fixed-bowl').boundingBox()
 await page.mouse.move(r.x+r.width*.4,r.y+r.height*.43);await page.mouse.down();await page.mouse.move(r.x+r.width*.55,r.y+r.height*.4,{steps:3})
 await expect(page.locator('.noodle-fold').first()).not.toHaveCSS('transform','matrix(1, 0, 0, 1, 0, 0)')
 expect(await page.locator('.fixed-bowl').boundingBox()).toEqual(fixedBefore)
 await expect(page.locator('.noodle-mouth')).toHaveCSS('overflow','hidden')
 await expect(page.locator('.noodle-mouth')).toHaveCSS('clip-path',/ellipse/)
 await page.screenshot({path:testInfo.outputPath('stirring.png'),fullPage:true})
 await page.mouse.up();await expect(page.locator('.noodle-fold').first()).toHaveCSS('transform','matrix(1, 0, 0, 1, 0, 0)')
 const before=await page.locator('.cook-phase').innerText();await button(page,'芝麻酱').click();await expect(page.locator('.cook-phase')).toHaveText(before)
 await page.mouse.move(r.x+r.width*.4,r.y+r.height*.43);await page.mouse.down();await bowl.dispatchEvent('pointercancel');const cancelled=await page.locator('.cook-phase').innerText();await page.mouse.move(r.x+r.width*.7,r.y+r.height*.43);await page.mouse.up();await expect(page.locator('.cook-phase')).toHaveText(cancelled)
})
